const BAG_KEY = "avdict:fortuneBag";
let memoryBag = [];
let lastIndex = null;
function shuffled() {
  const order = FORTUNES.map((_, i) => i);
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}
function loadBag() {
  try {
    const bag = JSON.parse(localStorage.getItem(BAG_KEY));
    if (Array.isArray(bag)) return bag.filter((i) => Number.isInteger(i) && i >= 0 && i < FORTUNES.length);
  } catch {
  }
  return memoryBag;
}
function saveBag(bag) {
  memoryBag = bag;
  try {
    localStorage.setItem(BAG_KEY, JSON.stringify(bag));
  } catch {
  }
}
export function nextFortune() {
  let bag = loadBag();
  if (bag.length === 0) {
    bag = shuffled();
    if (bag[bag.length - 1] === lastIndex && bag.length > 1) [bag[0], bag[bag.length - 1]] = [bag[bag.length - 1], bag[0]];
  }
  const index = bag.pop();
  lastIndex = index;
  saveBag(bag);
  return FORTUNES[index];
}
